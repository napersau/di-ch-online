'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { createApp } = require('../server');

test('HTTP: bảo vệ host, demo, đăng nhập, cấu hình và sự kiện realtime SSE', async t => {
  const app = createApp({ adminToken: 'test-host-key', persist: false, simulate: false });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(() => app.close());
  const base = `http://127.0.0.1:${app.server.address().port}`;
  const post = (route, body, headers = {}) => fetch(`${base}/api/${route}`, { method: 'POST', headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(body) });
  assert.equal((await fetch(base)).status, 200);
  assert.equal((await fetch(`${base}/overlay`)).status, 200);
  assert.equal((await post('settings', { goal: 500 })).status, 401);
  assert.equal((await post('demo', { name: 'Test', coins: 1 }, { Origin: 'https://foreign.example' })).status, 403);
  assert.equal((await post('login', { token: 'wrong' })).status, 401);
  const login = await post('login', { token: 'test-host-key' });
  assert.equal(login.status, 200);
  const cookie = login.headers.get('set-cookie').split(';')[0];
  assert.equal((await post('settings', { title: 'Chánh điện Test', goal: 500 }, { Cookie: cookie })).status, 200);
  assert.equal((await fetch(`${base}/api/state`).then(r => r.json())).settings.goal, 500);
  const abort = new AbortController();
  const stream = await fetch(`${base}/api/stream`, { signal: abort.signal });
  const reader = stream.body.getReader();
  assert.match(new TextDecoder().decode((await reader.read()).value), /event: state/);
  assert.equal((await post('demo', { name: '<script>alert(1)</script>', coins: 99 })).status, 200);
  let frames = '';
  while (!frames.includes('event: gift')) frames += new TextDecoder().decode((await reader.read()).value);
  assert.match(frames, /"coins":99/);
  abort.abort();
  assert.equal((await post('reset', { confirm: 'RESET', demo: false }, { Cookie: cookie })).status, 200);
  assert.equal((await post('demo', { name: 'fake', coins: 1 })).status, 401);
  assert.equal((await post('events', { type: 'gift', user: { id: 'real', name: 'Khách thật' }, coins: 30 }, { 'x-admin-token': 'test-host-key' })).status, 200);
  const state = await fetch(`${base}/api/state`).then(r => r.json());
  assert.equal(state.totalCoins, 30);
  assert.equal(state.visitorCount, 1);
  assert.equal((await post('announce', { message: 'Chúc bạn bình an.' }, { Cookie: cookie })).status, 200);
  assert.equal((await post('settings', { goal: -1 }, { Cookie: cookie })).status, 400);
  assert.equal((await post('connect', { username: '<invalid>' }, { Cookie: cookie })).status, 400);
  assert.equal((await post('logout', {}, { Cookie: cookie })).status, 200);
  assert.equal((await post('settings', { goal: 1000 }, { Cookie: cookie })).status, 401);
});
